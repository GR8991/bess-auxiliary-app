"""PDF engineering summary report (ReportLab, pure Python). Content = services.engineering_summary only."""
from __future__ import annotations

import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak, KeepTogether
from reportlab.graphics.shapes import Drawing, String
from reportlab.graphics.charts.barcharts import HorizontalBarChart, VerticalBarChart

from calculations.excel_semantics import isnumber, XLError
from services import engineering_summary as ES
from services.json_export import LIMITATIONS

NAVY = colors.HexColor("#0E1A2B")
BLUE = colors.HexColor("#2F6FDB")
GREY = colors.HexColor("#E7EBF0")
STATUS = {"PASS": "#2E7D4F", "FAIL": "#B3261E", "REVIEW": "#B26A00", "INCOMPLETE": "#B26A00", "NOT VERIFIED": "#6B5CA5",
          "NOT APPLICABLE": "#6B7280"}


def _fmt(v, nd=1):
    if isinstance(v, XLError):
        return v.code
    if v is None or v == "":
        return "–"
    if isnumber(v):
        return f"{v:,.{nd}f}"
    return str(v)


HDR_STYLE = ParagraphStyle("hdr", fontName="Helvetica-Bold", fontSize=7.5, leading=9, textColor=colors.white)


def _table(data, widths=None, head=True, font=8):
    if head and data:
        data = [[Paragraph(str(c), HDR_STYLE) if isinstance(c, str) else c for c in data[0]]] + list(data[1:])
    t = Table(data, colWidths=widths, repeatRows=1 if head else 0)
    st = [("FONT", (0, 0), (-1, -1), "Helvetica", font), ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#C5CDD8")),
          ("VALIGN", (0, 0), (-1, -1), "TOP"), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F5F7FA")])]
    if head:
        st += [("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", font)]
    t.setStyle(TableStyle(st))
    return t


def _bar(labels, values, title, unit, horizontal=True, ref=None):
    d = Drawing(170 * mm, 70 * mm)
    ch = HorizontalBarChart() if horizontal else VerticalBarChart()
    ch.x, ch.y, ch.width, ch.height = 30 * mm, 8 * mm, 130 * mm, 52 * mm
    ch.data = [[float(v) if isnumber(v) else 0 for v in values]] or [[0]]
    ch.categoryAxis.categoryNames = [str(l)[:14] for l in labels]
    ch.categoryAxis.labels.fontSize = 7
    ch.valueAxis.labels.fontSize = 7
    ch.valueAxis.valueMin = 0
    ch.bars[0].fillColor = BLUE
    d.add(ch)
    d.add(String(0, 66 * mm, f"{title} ({unit})", fontName="Helvetica-Bold", fontSize=9, fillColor=NAVY))
    return d


def build_pdf(project, res, user="") -> bytes:
    s = ES.build(project, res)
    bio = io.BytesIO()
    doc = SimpleDocTemplate(bio, pagesize=landscape(A4), leftMargin=14 * mm, rightMargin=14 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
                            title="BESS Auxiliary Engineering Summary", author=str(user or ""))
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], textColor=NAVY, fontSize=16)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=BLUE, fontSize=12, spaceBefore=8)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=8.5, leading=11)
    small = ParagraphStyle("s", parent=body, fontSize=7.5, textColor=colors.HexColor("#4B5563"))
    P = lambda t, st=body: Paragraph(str(t).replace("&", "&amp;").replace("<", "&lt;"), st)
    el = []
    p = s["project"]
    el += [P("BESS Auxiliary Load &amp; Transformer Sizing — Engineering Summary".replace("&amp;", "&"), h1),
           P(f"Project: {p['name'] or '–'} · Revision {p['revision'] or '–'} · Project ID {p['project_id']}", body),
           P(f"Calculation engine {res['engine_version']} · methodology of workbook v{res['source_workbook_version']} · prepared for "
             f"{p['prepared_by'] or '–'}; generated by {user or '–'}", small), Spacer(1, 4)]
    disp = s["disposition"]
    t = _table([[P(f"<b>OVERALL DISPOSITION: {disp}</b>".replace("<b>", "").replace("</b>", ""), body)], [P(s["disposition_note"], small)]],
               widths=[265 * mm], head=False)
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#FFF4E0")), ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#B26A00"))]))
    el += [t, Spacer(1, 6)]
    el.append(P("A. Project information", h2))
    rows = [["Project", p["name"], "Client", p["client"], "Location", p["location"]],
            ["Country / grid region", p["country_grid_region"], "Capacity (MW)", p["capacity_MW"], "Energy (MWh)", p["energy_MWh"]],
            ["Duration (h)", p["duration_h"], "POI voltage (kV)", p["poi_voltage_kV"], "Aux system voltage (V)", p["aux_voltage_V"]],
            ["Revision", p["revision"], "Prepared by", p["prepared_by"], "Reviewed by", p["reviewed_by"]], ["Date", p["date"], "", "", "", ""]]
    el.append(_table([[P(_fmt(c, 2), body) for c in r] for r in rows], widths=[38 * mm, 50 * mm] * 3, head=False))
    el.append(P("B. Input completion", h2))
    el.append(_table([["Module", "Status", "Detail"]] + [[c["module"], c["status"], P(c["detail"], small)] for c in s["completion"]],
                     widths=[45 * mm, 50 * mm, 170 * mm]))
    e = s["electrical"]
    el.append(P("C. Electrical design summary", h2))
    rows = [["Connected load", f"{_fmt(e['connected_kW'])} kW / {_fmt(e['connected_kVA'])} kVA", "Maximum-demand scenario", e["max_demand_scenario"]],
            ["Peak operating demand", f"{_fmt(e['operating_kW_peak'])} kW", "Peak reactive demand", f"{_fmt(e['reactive_kvar_peak'])} kvar"],
            ["Peak apparent demand", f"{_fmt(e['apparent_kVA_peak'])} kVA (PF {_fmt(e['peak_pf'], 3)})", "Transient incl. largest start", f"{_fmt(e['transient_kVA'])} kVA"],
            ["Transformers / feeders", f"{e['n_transformers']} / {e['n_feeders']}", "Max transformer demand", f"{_fmt(e['max_tx_demand_kVA'])} kVA"],
            ["Max transformer loading", f"{_fmt(e['max_tx_loading_pct'])} %", "Max feeder loading", f"{_fmt(e['max_feeder_loading_pct'])} %"],
            ["Max phase imbalance", f"{_fmt(e['max_phase_imbalance_pct'])} %", "Lagging / leading kvar (peak)", f"{_fmt(e['lagging_kvar_peak'])} / {_fmt(e['leading_kvar_peak'])}"],
            ["Daily auxiliary energy", f"{_fmt(e['daily_kWh'])} kWh/day", "DC loads (informative)", f"{_fmt(e['dc_kW'], 2)} kW"]]
    el.append(_table(rows, widths=[50 * mm, 82 * mm, 55 * mm, 78 * mm], head=False))
    sc = e["scenarios"]
    el.append(_bar(list(sc.keys()), [v["kVA"] for v in sc.values()], "Scenario apparent power", "kVA", horizontal=False))
    el.append(P("D. Transformer summary", h2))
    rows = [["Transformer", "Calculated demand kVA", "Calculated minimum kVA", "Recommended rating", "Selected rating", "Loading %", "Derating", "Result"]]
    for t_ in s["transformers"]:
        rows.append([t_["TX_ID"], _fmt(t_["Design_kVA"]), _fmt(t_["Req_min_kVA"]), _fmt(t_["Recommended"]), _fmt(t_["Selected"]),
                     _fmt(t_["Loading_pct"]), t_["Derating"], P(t_["Result"], small)])
    el.append(_table(rows, widths=[25 * mm, 32 * mm, 32 * mm, 30 * mm, 26 * mm, 20 * mm, 32 * mm, 68 * mm]))
    el.append(P("Recommended standard rating is not an approved selection. Loading % = calculated demand ÷ evaluated rating (R-6).", small))
    if s["transformers"]:
        el.append(_bar([t_["TX_ID"] for t_ in s["transformers"]], [t_["Loading_pct"] for t_ in s["transformers"]],
                       "Transformer loading", "% of evaluated rating"))
    v = s["validation"]
    el.append(P("E. Validation summary", h2))
    rc = v["register_counts"]
    el.append(_table([["Register checks", "PASS", "FAIL", "REVIEW", "INCOMPLETE", "NOT VERIFIED", "NOT APPLICABLE"],
                      [v["total"]] + [rc[k] for k in ("PASS", "FAIL", "REVIEW", "INCOMPLETE", "NOT VERIFIED", "NOT APPLICABLE")]],
                     widths=[35 * mm] + [32 * mm] * 6))
    hi = [x for x in res["application"]["register"] if x["status"] in ("FAIL", "INCOMPLETE", "REVIEW", "NOT VERIFIED")]
    el.append(_table([["ID", "Category", "Status", "Severity", "Recommended action"]] +
                     [[x["id"], x["category"], x["status"], x["severity"], P(x["action"], small)] for x in hi],
                     widths=[14 * mm, 35 * mm, 30 * mm, 20 * mm, 166 * mm]))
    hf = [x for x in res["application"]["findings"] if x["severity"] == "High"]
    if hf:
        el.append(P(f"High-severity row findings ({len(hf)})", h2))
        el.append(_table([["Object", "ID", "Code", "Status", "Description"]] +
                         [[x["object"], x["object_id"], x["code"], x["status"], P(x["description"], small)] for x in hf[:60]],
                         widths=[25 * mm, 30 * mm, 18 * mm, 28 * mm, 164 * mm]))
    el.append(PageBreak())
    el.append(P("F. Engineering limitations and unresolved items", h2))
    el.append(_table([["Category", "Item", "Reference", "Severity"]] +
                     [[P(u["category"], small), P(u["item"], small), P(u["reference"], small), u["severity"]] for u in s["unresolved"]],
                     widths=[50 * mm, 150 * mm, 45 * mm, 20 * mm]))
    el.append(Spacer(1, 4))
    for l in LIMITATIONS:
        el.append(P("• " + l, small))
    el.append(KeepTogether([P("G. Overall engineering disposition", h2), P(f"{disp}. {s['disposition_note']}", body)]))
    el.append(P("This report is generated from project inputs by a deterministic calculation engine; no AI model performed any calculation. "
                "Equipment values originate from the engineer; none are invented by the application.", small))

    def footer(c, d):
        c.saveState()
        c.setFont("Helvetica", 7)
        c.setFillColor(colors.HexColor("#6B7280"))
        c.drawString(14 * mm, 8 * mm, f"{p['name'] or 'Project'} · {p['revision'] or ''} · {disp}")
        c.drawRightString(283 * mm, 8 * mm, f"Page {d.page}")
        c.restoreState()
    doc.build(el, onFirstPage=footer, onLaterPages=footer)
    return bio.getvalue()
